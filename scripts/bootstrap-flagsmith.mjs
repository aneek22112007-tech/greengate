#!/usr/bin/env node
/**
 * Idempotent Flagsmith bootstrap for GreenGate.
 * Looks up each object before creating it. Writes secrets only to .env.
 * Never prints keys, passwords, or tokens.
 */
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const ENV_PATH = path.join(ROOT, '.env');
const BASE = (process.env.FLAGSMITH_BASE_URL || 'http://localhost:8100').replace(/\/$/, '');
const API = `${BASE}/api/v1`;

const ADMIN_EMAIL = process.env.FLAGSMITH_ADMIN_EMAIL || 'greengate-admin@example.com';
const ORG_NAME = 'GreenGate';
const PROJECT_NAME = 'GreenGate';
const ENV_NAMES = ['Development', 'Production'];

function redact(text) {
  return String(text)
    .replace(/ser\.[A-Za-z0-9_-]+/g, 'ser.[redacted]')
    .replace(/"(key|token|password|api_key|server_side_api_key)"\s*:\s*"[^"]*"/g, '"$1":"[redacted]"');
}

function log(message) {
  console.log(message);
}

function parseEnv(text) {
  const out = {};
  for (const line of text.split('\n')) {
    const trimmed = line.trim();
    if (!trimmed || trimmed.startsWith('#')) continue;
    const eq = trimmed.indexOf('=');
    if (eq === -1) continue;
    const key = trimmed.slice(0, eq).trim();
    let value = trimmed.slice(eq + 1).trim();
    if ((value.startsWith('"') && value.endsWith('"')) || (value.startsWith("'") && value.endsWith("'"))) {
      value = value.slice(1, -1);
    }
    out[key] = value;
  }
  return out;
}

function loadDotEnv() {
  if (!fs.existsSync(ENV_PATH)) return {};
  return parseEnv(fs.readFileSync(ENV_PATH, 'utf8'));
}

function writeDotEnv(values) {
  const existing = fs.existsSync(ENV_PATH) ? parseEnv(fs.readFileSync(ENV_PATH, 'utf8')) : {};
  const merged = { ...existing, ...values };
  const exampleOrder = [
    'FLAGSMITH_API_URL',
    'FLAGSMITH_EVENTS_URL',
    'FLAGSMITH_ENVIRONMENT_KEY_DEVELOPMENT',
    'FLAGSMITH_ENVIRONMENT_KEY_PRODUCTION',
    'FLAGSMITH_CLIENT_KEY_DEVELOPMENT',
    'FLAGSMITH_CLIENT_KEY_PRODUCTION',
    'FLAGSMITH_ORGANISATION_API_KEY',
    'FLAGSMITH_PROJECT_ID',
    'FLAGSMITH_ENVIRONMENT_ID_DEVELOPMENT',
    'FLAGSMITH_ENVIRONMENT_KEY_ID_DEVELOPMENT',
    'FLAGSMITH_ADMIN_EMAIL',
    'FLAGSMITH_ADMIN_PASSWORD',
    'ELECTRICITY_MAPS_TOKEN',
    'GREENGATE_MOCK_LEVEL',
    'GREENGATE_DEFAULT_ZONE',
    'GREENGATE_MAPPING',
    'LLM_API_KEY',
    'LLM_BASE_URL',
    'LLM_MODEL',
    'NODE_ENV',
    'PORT',
  ];
  const keys = [...exampleOrder.filter((key) => merged[key] !== undefined)];
  for (const key of Object.keys(merged)) {
    if (!keys.includes(key)) keys.push(key);
  }
  const lines = [
    '# Generated by scripts/bootstrap-flagsmith.mjs. Gitignored. Do not commit.',
    ...keys.map((key) => `${key}=${merged[key] ?? ''}`),
    '',
  ];
  fs.writeFileSync(ENV_PATH, lines.join('\n'), { mode: 0o600 });
  fs.chmodSync(ENV_PATH, 0o600);
}

async function request(method, url, { token, envKey, body, tolerate } = {}) {
  const headers = { Accept: 'application/json' };
  if (body !== undefined) headers['Content-Type'] = 'application/json';
  if (token) headers.Authorization = `Token ${token}`;
  if (envKey) headers['X-Environment-Key'] = envKey;
  const response = await fetch(url, {
    method,
    headers,
    body: body !== undefined ? JSON.stringify(body) : undefined,
  });
  const text = await response.text();
  let json = null;
  if (text) {
    try {
      json = JSON.parse(text);
    } catch {
      json = null;
    }
  }
  if (!response.ok && !(tolerate || []).includes(response.status)) {
    throw new Error(`${method} ${url.replace(BASE, '')} -> ${response.status} ${redact(text).slice(0, 800)}`);
  }
  return { status: response.status, json, text };
}

async function listAll(token, pathAndQuery) {
  const items = [];
  let next = pathAndQuery.startsWith('http') ? pathAndQuery : `${API}${pathAndQuery}`;
  for (let page = 0; page < 20 && next; page += 1) {
    const { json } = await request('GET', next, { token });
    if (Array.isArray(json)) return json;
    items.push(...(json?.results || []));
    if (!json?.next) break;
    const nextUrl = new URL(json.next);
    next = `${BASE}${nextUrl.pathname}${nextUrl.search}`;
  }
  return items;
}

function byName(items, name) {
  return items.find((item) => item.name === name);
}

async function waitForHealth() {
  const url = `${BASE}/health/liveness/`;
  const deadline = Date.now() + 180_000;
  let last = 'not started';
  while (Date.now() < deadline) {
    try {
      const response = await fetch(url);
      if (response.status === 200) {
        log(`health ${url} -> 200`);
        return;
      }
      last = String(response.status);
    } catch (error) {
      last = error instanceof Error ? error.message : String(error);
    }
    await new Promise((resolve) => setTimeout(resolve, 2000));
  }
  throw new Error(`Flagsmith health check timed out (${last})`);
}

async function versionInfo() {
  const { json } = await request('GET', `${BASE}/version/`);
  const selfHosted = json?.self_hosted_data || {};
  log(
    `version experimentation_enabled=${json?.experimentation_enabled} has_users=${selfHosted.has_users}`,
  );
  return json || {};
}

async function adminToken(fileEnv, version) {
  const hasUsers = Boolean(version?.self_hosted_data?.has_users);
  const password = fileEnv.FLAGSMITH_ADMIN_PASSWORD;
  if (hasUsers) {
    if (!password || password === 'replace-me') {
      throw new Error('Flagsmith already has users but .env has no FLAGSMITH_ADMIN_PASSWORD.');
    }
    const { json } = await request('POST', `${API}/auth/login/`, {
      body: { email: fileEnv.FLAGSMITH_ADMIN_EMAIL || ADMIN_EMAIL, password },
    });
    log('reused admin login');
    return { token: json.key, password, created: false };
  }
  const generated = password && password !== 'replace-me' ? password : crypto.randomBytes(24).toString('base64url');
  const { json } = await request('POST', `${API}/auth/users/`, {
    body: {
      email: ADMIN_EMAIL,
      password: generated,
      re_password: generated,
      first_name: 'GreenGate',
      last_name: 'Admin',
      superuser: true,
    },
  });
  // Persist before any later step can fail, or a retry cannot log in.
  writeDotEnv({
    FLAGSMITH_ADMIN_EMAIL: ADMIN_EMAIL,
    FLAGSMITH_ADMIN_PASSWORD: generated,
    FLAGSMITH_API_URL: `${API}/`,
    FLAGSMITH_EVENTS_URL: `${BASE}/api/`,
  });
  log('created admin user and stored the password in .env');
  return { token: json.key, password: generated, created: true };
}

async function ensureOrg(token) {
  const orgs = await listAll(token, '/organisations/?page_size=100');
  const existing = byName(orgs, ORG_NAME);
  if (existing) {
    log(`reused organisation ${ORG_NAME} id=${existing.id}`);
    return existing;
  }
  const { json } = await request('POST', `${API}/organisations/`, { token, body: { name: ORG_NAME } });
  log(`created organisation ${ORG_NAME} id=${json.id}`);
  return json;
}

async function ensureMasterKey(token, orgId, fileEnv) {
  if (fileEnv.FLAGSMITH_ORGANISATION_API_KEY && fileEnv.FLAGSMITH_ORGANISATION_API_KEY !== 'replace-me') {
    log('reused organisation API key from .env');
    return fileEnv.FLAGSMITH_ORGANISATION_API_KEY;
  }
  const { json } = await request('POST', `${API}/organisations/${orgId}/master-api-keys/`, {
    token,
    body: { name: 'GreenGate bootstrap', is_admin: true },
  });
  if (!json?.key) throw new Error('Organisation API key response had no key');
  writeDotEnv({ FLAGSMITH_ORGANISATION_API_KEY: json.key });
  log('created organisation API key');
  return json.key;
}

async function ensureProject(token, orgId) {
  const projects = await listAll(token, `/projects/?organisation=${orgId}&page_size=100`);
  const existing = byName(projects, PROJECT_NAME);
  if (existing) {
    log(`reused project ${PROJECT_NAME} id=${existing.id}`);
    return existing;
  }
  const { json } = await request('POST', `${API}/projects/`, {
    token,
    body: { name: PROJECT_NAME, organisation: orgId },
  });
  log(`created project ${PROJECT_NAME} id=${json.id}`);
  return json;
}

async function ensureEnvironment(token, projectId, name) {
  const environments = await listAll(token, `/environments/?project=${projectId}&page_size=100`);
  const existing = byName(environments, name);
  if (existing) {
    log(`reused environment ${name} id=${existing.id}`);
    return existing;
  }
  const { json } = await request('POST', `${API}/environments/`, {
    token,
    body: { name, project: projectId },
  });
  log(`created environment ${name} id=${json.id}`);
  return json;
}

async function ensureServerKey(token, environment, fileEnv) {
  const slot = environment.name === 'Development' ? 'DEVELOPMENT' : 'PRODUCTION';
  const envName = `FLAGSMITH_ENVIRONMENT_KEY_${slot}`;
  if (fileEnv[envName] && fileEnv[envName] !== 'ser.replace-me') {
    log(`reused server key for ${environment.name}`);
    return fileEnv[envName];
  }
  // Server-side keys are addressed by the environment API key, not the numeric id.
  const listed = await request('GET', `${API}/environments/${environment.api_key}/api-keys/`, { token });
  const keys = Array.isArray(listed.json) ? listed.json : listed.json?.results || [];
  const named = keys.find((item) => item.name === 'GreenGate server' && typeof item.key === 'string' && item.key.startsWith('ser.'));
  if (named) {
    writeDotEnv({ [envName]: named.key });
    log(`reused server key for ${environment.name} from API`);
    return named.key;
  }
  const { json } = await request('POST', `${API}/environments/${environment.api_key}/api-keys/`, {
    token,
    body: { name: 'GreenGate server' },
  });
  if (!json?.key) throw new Error(`Server key for ${environment.name} was created without a key field`);
  log(`created server key for ${environment.name}`);
  writeDotEnv({ [envName]: json.key });
  return json.key;
}

async function ensureFeature(token, projectId, spec) {
  const features = await listAll(token, `/projects/${projectId}/features/?page_size=100`);
  const existing = byName(features, spec.name);
  if (existing) {
    log(`reused feature ${spec.name} id=${existing.id}`);
    return existing;
  }
  const { json } = await request('POST', `${API}/projects/${projectId}/features/`, { token, body: spec });
  log(`created feature ${spec.name} id=${json.id}`);
  return json;
}

async function ensureVariants(token, projectId, feature) {
  const detail = await request('GET', `${API}/projects/${projectId}/features/${feature.id}/`, { token });
  const current = detail.json?.multivariate_options || [];
  const wanted = [
    { key: 'full', string_value: 'full' },
    { key: 'eco', string_value: 'eco' },
    { key: 'off', string_value: 'off' },
  ];
  for (const variant of wanted) {
    const found = current.find((item) => item.string_value === variant.string_value || item.key === variant.key);
    if (found) {
      log(`reused variant ${variant.string_value}`);
      continue;
    }
    const body = {
      feature: feature.id,
      type: 'unicode',
      string_value: variant.string_value,
      default_percentage_allocation: 0,
      key: variant.key,
    };
    const created = await request('POST', `${API}/projects/${projectId}/features/${feature.id}/mv-options/`, {
      token,
      body,
      tolerate: [400],
    });
    if (created.status === 400) {
      const retry = { ...body };
      delete retry.key;
      const second = await request('POST', `${API}/projects/${projectId}/features/${feature.id}/mv-options/`, {
        token,
        body: retry,
        tolerate: [400],
      });
      if (second.status === 400) {
        throw new Error(`variant ${variant.string_value} rejected: ${redact(created.text).slice(0, 400)} | retry: ${redact(second.text).slice(0, 400)}`);
      }
      log(`created variant ${variant.string_value} without key field`);
    } else {
      log(`created variant ${variant.string_value}`);
    }
  }
}

async function ensureSegment(token, projectId, name, level) {
  const segments = await listAll(token, `/projects/${projectId}/segments/?page_size=100`);
  const existing = byName(segments, name);
  if (existing) {
    log(`reused segment ${name} id=${existing.id}`);
    return existing;
  }
  const { json } = await request('POST', `${API}/projects/${projectId}/segments/`, {
    token,
    body: {
      name,
      description: `Identity trait carbon_level is ${level}`,
      rules: [
        {
          type: 'ALL',
          rules: [
            {
              type: 'ANY',
              conditions: [
                {
                  operator: 'EQUAL',
                  property: 'carbon_level',
                  value: level,
                },
              ],
            },
          ],
        },
      ],
    },
  });
  log(`created segment ${name} id=${json.id}`);
  return json;
}

async function featureStates(token, environment) {
  return listAll(token, `/environments/${environment.api_key}/featurestates/?page_size=200`);
}

async function ensureSegmentOverride(token, feature, segment, environment, value, priority) {
  // The environment featurestates list hides segment overrides. The feature-scoped
  // list includes them, and feature_segment is the numeric feature-segment id.
  const featureSegments = await listAll(
    token,
    `/features/feature-segments/?environment=${environment.id}&feature=${feature.id}&page_size=100`,
  );
  let featureSegment = featureSegments.find((item) => (item.segment?.id || item.segment) === segment.id);
  if (!featureSegment) {
    const created = await request('POST', `${API}/features/feature-segments/`, {
      token,
      body: {
        feature: feature.id,
        segment: segment.id,
        environment: environment.id,
        priority,
      },
    });
    featureSegment = created.json;
  }

  const states = await listAll(
    token,
    `/features/featurestates/?feature=${feature.id}&environment=${environment.id}&page_size=100`,
  );
  const existing = states.find(
    (state) => state.feature_segment === featureSegment.id || state.feature_segment?.id === featureSegment.id,
  );
  if (existing) {
    const current = typeof existing.feature_state_value === 'string'
      ? existing.feature_state_value
      : existing.feature_state_value?.string_value;
    log(`reused segment override ${segment.name} -> ${current} in ${environment.name}`);
    return existing;
  }

  const { json } = await request('POST', `${API}/features/featurestates/`, {
    token,
    body: {
      feature: feature.id,
      feature_segment: featureSegment.id,
      environment: environment.id,
      enabled: true,
      feature_state_value: {
        type: 'unicode',
        string_value: value,
      },
    },
  });
  log(`created segment override ${segment.name} -> ${value} in ${environment.name}`);
  return json;
}

async function ensureControlValue(token, environment, feature) {
  const states = await featureStates(token, environment);
  const state = states.find((item) => {
    const featureId = item.feature?.id || item.feature;
    return featureId === feature.id && !item.feature_segment;
  });
  if (!state) {
    log(`no base feature state for ${feature.name} in ${environment.name}`);
    return;
  }
  const value = typeof state.feature_state_value === 'string' ? state.feature_state_value : state.feature_state_value?.string_value;
  if (state.enabled && value === 'full') {
    log(`reused control value full for ${feature.name} in ${environment.name}`);
    return;
  }
  await request('PATCH', `${API}/environments/${environment.api_key}/featurestates/${state.id}/`, {
    token,
    body: {
      enabled: true,
      feature_state_value: { type: 'unicode', string_value: 'full' },
    },
    tolerate: [404],
  }).catch(async () => {
    await request('PUT', `${API}/features/featurestates/${state.id}/`, {
      token,
      body: {
        enabled: true,
        feature: feature.id,
        environment: environment.id,
        feature_state_value: { type: 'unicode', string_value: 'full' },
      },
    });
  });
  log(`set control value full for ${feature.name} in ${environment.name}`);
}

async function ensureWarehouse(token, environment) {
  const key = environment.api_key;
  const listed = await request('GET', `${API}/environments/${key}/warehouse-connections/`, { token });
  const connections = Array.isArray(listed.json) ? listed.json : listed.json?.results || [];
  if (connections.some((item) => item.status === 'connected' || item.warehouse_type === 'postgres')) {
    log(`reused warehouse connection in ${environment.name}`);
    return;
  }
  const created = await request('POST', `${API}/environments/${key}/warehouse-connections/`, {
    token,
    body: { warehouse_type: 'postgres', config: { source: 'flagsmith_database' } },
  });
  log(`warehouse ${environment.name} status=${created.json?.status || 'created'}`);
}

function flagValue(flags, name) {
  const flag = (flags || []).find((item) => (item.feature?.name || item.feature_name || item.name) === name);
  if (!flag) return null;
  if (typeof flag.feature_state_value === 'string') return flag.feature_state_value;
  if (flag.feature_state_value && typeof flag.feature_state_value === 'object') {
    return flag.feature_state_value.string_value ?? null;
  }
  return flag.value ?? null;
}

async function verifyRouting(serverKey) {
  const cases = [
    ['low', 'full'],
    ['moderate', 'eco'],
    ['high', 'off'],
  ];
  for (const [level, expected] of cases) {
    const { json } = await request('POST', `${API}/identities/`, {
      envKey: serverKey,
      body: {
        identifier: `greengate-verify-${level}`,
        traits: [{ trait_key: 'carbon_level', trait_value: level }],
      },
    });
    const actual = flagValue(json?.flags, 'heavy_feature_mode');
    const enabled = (json?.flags || []).find((item) => (item.feature?.name || item.name) === 'greengate_enabled');
    log(`verify carbon_level=${level} -> ${actual} (expected ${expected}); greengate_enabled=${enabled?.enabled}`);
    if (actual !== expected) {
      throw new Error(`Routing check failed for ${level}: got ${actual}, expected ${expected}`);
    }
  }
  log('verify routing ok');
}

async function main() {
  await waitForHealth();
  const version = await versionInfo();
  const fileEnv = loadDotEnv();
  const admin = await adminToken(fileEnv, version);
  const org = await ensureOrg(admin.token);
  const orgKey = await ensureMasterKey(admin.token, org.id, fileEnv);
  const project = await ensureProject(admin.token, org.id);
  const environments = [];
  for (const name of ENV_NAMES) {
    environments.push(await ensureEnvironment(admin.token, project.id, name));
  }

  const heavy = await ensureFeature(admin.token, project.id, {
    name: 'heavy_feature_mode',
    type: 'MULTIVARIATE',
    initial_value: 'full',
    default_enabled: true,
    description: 'How heavy the AI summary is allowed to be: full, eco, or off.',
  });
  await ensureVariants(admin.token, project.id, heavy);
  const kill = await ensureFeature(admin.token, project.id, {
    name: 'greengate_enabled',
    type: 'STANDARD',
    initial_value: 'true',
    default_enabled: true,
    description: 'Kill switch. Off forces the full variant.',
  });

  const high = await ensureSegment(admin.token, project.id, 'carbon_high', 'high');
  const moderate = await ensureSegment(admin.token, project.id, 'carbon_moderate', 'moderate');

  const serverKeys = {};
  const clientKeys = {};
  for (const environment of environments) {
    serverKeys[environment.name] = await ensureServerKey(admin.token, environment, fileEnv);
    clientKeys[environment.name] = environment.api_key;
    await ensureControlValue(admin.token, environment, heavy);
    await ensureSegmentOverride(admin.token, heavy, high, environment, 'off', 0);
    await ensureSegmentOverride(admin.token, heavy, moderate, environment, 'eco', 1);
    await ensureWarehouse(admin.token, environment);
  }

  const development = environments.find((item) => item.name === 'Development');
  writeDotEnv({
    FLAGSMITH_API_URL: `${API}/`,
    FLAGSMITH_EVENTS_URL: `${BASE}/api/`,
    FLAGSMITH_ENVIRONMENT_KEY_DEVELOPMENT: serverKeys.Development,
    FLAGSMITH_ENVIRONMENT_KEY_PRODUCTION: serverKeys.Production,
    FLAGSMITH_CLIENT_KEY_DEVELOPMENT: clientKeys.Development,
    FLAGSMITH_CLIENT_KEY_PRODUCTION: clientKeys.Production,
    FLAGSMITH_ORGANISATION_API_KEY: orgKey,
    FLAGSMITH_PROJECT_ID: String(project.id),
    FLAGSMITH_ENVIRONMENT_ID_DEVELOPMENT: String(development.id),
    FLAGSMITH_ADMIN_EMAIL: fileEnv.FLAGSMITH_ADMIN_EMAIL || ADMIN_EMAIL,
    FLAGSMITH_ADMIN_PASSWORD: admin.password,
    GREENGATE_DEFAULT_ZONE: fileEnv.GREENGATE_DEFAULT_ZONE || 'IN-SO',
    GREENGATE_MAPPING: fileEnv.GREENGATE_MAPPING || 'strict',
    NODE_ENV: fileEnv.NODE_ENV || 'development',
    PORT: fileEnv.PORT || '3000',
    ELECTRICITY_MAPS_TOKEN: fileEnv.ELECTRICITY_MAPS_TOKEN || '',
    GREENGATE_MOCK_LEVEL: fileEnv.GREENGATE_MOCK_LEVEL || '',
    LLM_API_KEY: fileEnv.LLM_API_KEY || '',
    LLM_BASE_URL: fileEnv.LLM_BASE_URL || '',
    LLM_MODEL: fileEnv.LLM_MODEL || 'gpt-4o-mini',
  });
  log(`wrote ${ENV_PATH} (mode 600). Secrets were not printed.`);
  log(`project id=${project.id} kill_switch id=${kill.id} environments=${environments.map((item) => item.id).join(',')}`);

  await verifyRouting(serverKeys.Development);
}

main().catch((error) => {
  console.error(redact(error instanceof Error ? error.stack || error.message : String(error)));
  process.exit(1);
});
